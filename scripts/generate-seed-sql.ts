/**
 * Emits supabase/seed.sql from the TypeScript seed (single source of truth).
 * Demo members, and per-user tables, are excluded: Supabase profiles must belong to
 * real auth users. Usage: npm run db:seed:sql
 */
import { rowToDb } from "../src/lib/server/store/supabase";
import { TABLES, type Collection } from "../src/lib/domain/types";
import { buildSeedDatabase } from "../src/lib/seed/build";

// Parent tables first so foreign keys resolve.
const ORDER: Collection[] = [
  "tracks", "subtracks", "settings", "milestones", "sprints", "resources", "repositories", "researchTodos",
  "tasks", "checklistItems", "dependencies", "deliverables", "acceptanceCriteria", "taskResources", "statusHistory",
  "learningPaths", "learningModules", "documents", "documentRevisions", "metricDefinitions", "components", "externalDependencies", "auditEvents",
];

const db = buildSeedDatabase();
const out: string[] = ["-- Generated by scripts/generate-seed-sql.ts — do not edit by hand.", "begin;"];
for (const c of ORDER) {
  const rows = (db[c] as unknown as Record<string, unknown>[]).map(rowToDb);
  if (!rows.length) continue;
  const json = JSON.stringify(rows).replace(/'/g, "''");
  out.push(`insert into ${TABLES[c]} select * from jsonb_populate_recordset(null::${TABLES[c]}, '${json}'::jsonb) on conflict (id) do nothing;`);
}
out.push("commit;");
process.stdout.write(out.join("\n") + "\n");
